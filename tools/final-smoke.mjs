import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',headless:'new',args:['--no-sandbox','--enable-unsafe-swiftshader','--use-angle=swiftshader','--autoplay-policy=no-user-gesture-required','--hide-scrollbars'],defaultViewport:{width:1600,height:1000}});
const p = await b.newPage(); const errs=[];
p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
await p.goto('http://127.0.0.1:8777/web/',{waitUntil:'domcontentloaded'});
await p.waitForFunction('window.__ECHOSTAGE__?.state?.score',{timeout:30000});
await new Promise(r=>setTimeout(r,700));
await p.click('#btn-play'); await new Promise(r=>setTimeout(r,900));
const play=await p.evaluate(()=>({playing:window.__ECHOSTAGE__.state.playing,t:window.__ECHOSTAGE__.state.audio.currentTime,shot:window.__ECHOSTAGE__.stage.shot}));
await p.click('#btn-play');
await p.click('#btn-playlist'); await new Promise(r=>setTimeout(r,500));
await p.type('#playlist-url','https://music.163.com/playlist?id=3778678');
await p.click('#btn-fetch-playlist');
await p.waitForFunction(()=>document.querySelectorAll('#playlist .track-row').length>=100,{timeout:30000});
await new Promise(r=>setTimeout(r,700));
const list=await p.evaluate(()=>({rows:document.querySelectorAll('#playlist .track-row').length,label:document.querySelector('#playlist-count').textContent,firstBtn:document.querySelector('#playlist .track-load')?.textContent}));
await p.screenshot({path:'docs/reference/playlist.png'});
console.log({play,list,errs:errs.length?errs:'none'});
